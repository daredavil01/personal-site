#!/usr/bin/env node
/**
 * generate-guide-audio.mjs — the Atlas guide's four speech beats, spoken.
 *
 *   npm run atlas:voice
 *
 * The lines in src/atlas/guide/guideBeats.js are fixed, few and English, so
 * this is build-time work: Workers AI speaks them once, ffmpeg packs the takes
 * into one sprite, and the browser plays offsets out of it. No endpoint, no
 * request-time model call, no new consent UI — the sound toggle the Atlas
 * already has is the gate, and playSfx/playVoice is already how the UI fires
 * audio without importing the audio manager.
 *
 * Output:
 *   public/audio/guide-voice.m4a        the sprite (committed, ≤ 200 KB)
 *   src/atlas/audio/guideVoiceMap.js    offsets, GENERATED — never hand-edited
 *
 * The map is written rather than maintained because sfxMap.js carries a "MUST
 * match the table in generate-atlas-audio.mjs" comment, and a second pair of
 * files to keep in step by hand is a second pair to get wrong.
 *
 * Needs CF_ACCOUNT_ID / CF_API_TOKEN in .env (the same pair as embeddings) and
 * ffmpeg, on PATH or via `npm i --no-save ffmpeg-static`.
 */

import { execFileSync } from "node:child_process";
import {
  mkdirSync, writeFileSync, readFileSync, rmSync, statSync, existsSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { BEATS } from "../src/atlas/guide/guideBeats.js";
import { findFfmpeg } from "./generate-atlas-audio.mjs";
import { runWorkersAi } from "./lib/workersAi.mjs";

const MODEL = "@cf/deepgram/aura-2-en";
const SR = 44100;
// A breath between beats, so two takes played back to back never sound joined.
const GAP = 0.25;
// Speech is narrowband next to an ambient bed, so a low bitrate is transparent
// here. 48k put four beats at 195 KB — inside the 200 KB budget every other
// audio file observes, but with no room for a fifth line. 40k leaves some.
const BITRATE = "40k";
const BUDGET = 200 * 1024;

const OUT_DIR = path.resolve("public/audio");
const MAP_FILE = path.resolve("src/atlas/audio/guideVoiceMap.js");
const TMP_DIR = path.join(tmpdir(), "atlas-guide-voice");

function loadEnv() {
  const file = path.resolve(".env");
  if (!existsSync(file)) return;
  readFileSync(file, "utf8").split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  });
}

/**
 * The samples of a WAV file.
 *
 * ffmpeg writes a LIST chunk before the data on some builds, so the chunks are
 * walked rather than assuming the 44-byte header every example shows.
 */
function readWavMono(buf) {
  let at = 12; // past "RIFF<size>WAVE"
  while (at + 8 <= buf.length) {
    const id = buf.toString("ascii", at, at + 4);
    const size = buf.readUInt32LE(at + 4);
    if (id === "data") {
      const samples = new Float32Array(size / 2);
      for (let i = 0; i < samples.length; i += 1) {
        samples[i] = buf.readInt16LE(at + 8 + i * 2) / 32768;
      }
      return samples;
    }
    at += 8 + size + (size % 2);
  }
  throw new Error("no data chunk in the decoded WAV");
}

function toWav(samples) {
  const data = Buffer.alloc(samples.length * 2);
  samples.forEach((v, i) => {
    const clamped = Math.max(-1, Math.min(1, v));
    data.writeInt16LE(Math.round(clamped * 32767), i * 2);
  });
  const header = Buffer.alloc(44);
  header.write("RIFF");
  header.writeUInt32LE(36 + data.length, 4);
  header.write("WAVE", 8);
  header.write("fmt ", 12);
  header.writeUInt32LE(16, 16);
  header.writeUInt16LE(1, 20);
  header.writeUInt16LE(1, 22);
  header.writeUInt32LE(SR, 24);
  header.writeUInt32LE(SR * 2, 28);
  header.writeUInt16LE(2, 32);
  header.writeUInt16LE(16, 34);
  header.write("data", 36);
  header.writeUInt32LE(data.length, 40);
  return Buffer.concat([header, data]);
}

function writeMap(entries) {
  const rows = entries
    // Quoted only when it has to be: eslint's quote-props runs over the
    // generated file like any other.
    .map(({ id, offset, duration }) => {
      const key = /^[A-Za-z_$][\w$]*$/.test(id) ? id : `"${id}"`;
      return `  ${key}: [${offset.toFixed(2)}, ${duration.toFixed(2)}],`;
    })
    .join("\n");
  writeFileSync(
    MAP_FILE,
    `// GENERATED by scripts/generate-guide-audio.mjs (npm run atlas:voice).\n`
    + `// [offset, duration] seconds into public/audio/guide-voice.m4a, one entry\n`
    + `// per beat id in src/atlas/guide/guideBeats.js. Do not edit by hand —\n`
    + `// re-run the script after changing a line the guide says.\n`
    + `\nconst GUIDE_VOICE_MAP = {\n${rows}\n};\n\nexport default GUIDE_VOICE_MAP;\n`,
    "utf8",
  );
}

async function main() {
  loadEnv();
  const ffmpeg = await findFfmpeg();
  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(TMP_DIR, { recursive: true });

  const takes = [];
  for (const beat of BEATS) {
    // eslint-disable-next-line no-await-in-loop
    const mp3 = await runWorkersAi(MODEL, { text: beat.text }, { raw: true });
    const mp3Path = path.join(TMP_DIR, `${beat.id}.mp3`);
    const wavPath = path.join(TMP_DIR, `${beat.id}.wav`);
    writeFileSync(mp3Path, mp3);
    execFileSync(
      ffmpeg,
      ["-y", "-i", mp3Path, "-ac", "1", "-ar", String(SR), wavPath],
      { stdio: "ignore" },
    );
    const samples = readWavMono(readFileSync(wavPath));
    takes.push({ id: beat.id, samples });
    console.log(`  ${beat.id}  ${(samples.length / SR).toFixed(2)} s`);
  }

  const gap = Math.floor(GAP * SR);
  const totalSamples = takes.reduce((n, t) => n + t.samples.length + gap, 0);
  const sprite = new Float32Array(totalSamples);
  const entries = [];
  let at = 0;
  takes.forEach((take) => {
    sprite.set(take.samples, at);
    entries.push({
      id: take.id,
      offset: at / SR,
      duration: take.samples.length / SR,
    });
    at += take.samples.length + gap;
  });

  const spriteWav = path.join(TMP_DIR, "guide-voice.wav");
  writeFileSync(spriteWav, toWav(sprite));
  const outPath = path.join(OUT_DIR, "guide-voice.m4a");
  execFileSync(
    ffmpeg,
    ["-y", "-i", spriteWav, "-ac", "1", "-c:a", "aac", "-b:a", BITRATE, outPath],
    { stdio: "ignore" },
  );

  const bytes = statSync(outPath).size;
  console.log(`\nguide-voice.m4a  ${(bytes / 1024).toFixed(0)} KB  ${(at / SR).toFixed(1)} s`);
  if (bytes > BUDGET) {
    throw new Error("guide-voice.m4a exceeds the 200 KB budget — shorten a beat or drop the bitrate");
  }

  writeMap(entries);
  console.log(`map -> ${path.relative(process.cwd(), MAP_FILE)}`);

  if (existsSync(TMP_DIR)) rmSync(TMP_DIR, { recursive: true, force: true });
}

main().catch((err) => {
  console.error(`\n${err.message || err}`);
  process.exit(1);
});
