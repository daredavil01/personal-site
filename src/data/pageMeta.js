// "About" -> "About | Sanket Tambare"; null -> "Sanket Tambare"
export function composeTitle(title) {
  return title ? `${title} | ${SITE_NAME}` : SITE_NAME;
}

// Per-item meta builders.
//
// Pure and import-free so both the client detail pages and the esbuild-bundled
// Cloudflare middleware share ONE derivation per content type and cannot drift.
// Each caller extracts the item fields (client camelCase / REST snake_case) and
// passes normalised primitives in.
//
// Every builder returns { title, description, image, imageAlt, type }:
//   - `title` is BARE; callers wrap it via composeTitle / Helmet's titleTemplate
//   - `image` is the ROW'S OWN photo when the caller has one, and the section's
//     committed card when it does not — never a bare logo. Books, blogs, decks,
//     tags and shares have no photo at all, so they always take the card
//   - `type` is the og:type. Detail pages are "article", which is what they are;
//     the old code hardcoded "website" for every route on the site.
const truncate = (str, max) => (str.length > max ? `${str.slice(0, max - 3)}…` : str);

const sectionImage = (slug) => `${SITE_URL}/og/${slug}.png`;

export function buildMicroblogMeta({ title, text, date, image } = {}) {
  const raw = (text || title || "").replace(/\s+/g, " ").trim();
  const metaTitle = raw ? truncate(raw, 70) : `Post · ${date}`;
  const description = raw ? truncate(raw, 160) : "A micro-blog post.";
  return {
    title: metaTitle,
    description,
    image: image || sectionImage("micro-blog"),
    imageAlt: `Micro-blog post: ${metaTitle}`,
    type: "article",
  };
}

